"""Trunk-base keypoint detector (one box + one keypoint per tree) on the route-grouped Bangladesh split.
Generated by build_jobs.py, which fills in the __TOKENS__. Runs as a Kaggle GPU script with the
roadside-trees-of-bangladesh-street-view data set attached. Outputs: results_<NAME>.json, test_preds_<NAME>.csv, <NAME>_best.pt.
"""
import os, glob, json, csv, io, time, subprocess, math
subprocess.run("pip install -q ultralytics", shell=True)
from ultralytics import YOLO
SPLIT_CSV = """__SPLIT_CSV__"""
LABELS = json.loads(r"""__LABELS_JSON__""")
R = glob.glob('/kaggle/input/**/roadside-trees-of-bangladesh-street-view', recursive=True)[0]
src = {'BD_740': f'{R}/Train/BD_740', 'BD_755': f'{R}/Train/BD_755', 'BD_Test_Set_270': f'{R}/Test/BD_Test_Set_270'}
D='/kaggle/temp/pose'
for s in ['train','val','test']: os.makedirs(f'{D}/images/{s}',exist_ok=True); os.makedirs(f'{D}/labels/{s}',exist_ok=True)
for r in csv.DictReader(io.StringIO(SPLIT_CSV)):
    st=f"{r['folder']}_{r['id']}"; os.symlink(f"{src[r['folder']]}/{r['id']}.jpg", f"{D}/images/{r['split']}/{st}.jpg")
    open(f"{D}/labels/{r['split']}/{st}.txt",'w').write("\n".join(LABELS.get(st,[]))+"\n")
open(f'{D}/data.yaml','w').write(f"path: {D}\ntrain: images/train\nval: images/val\ntest: images/test\nkpt_shape: [1, 3]\nflip_idx: [0]\nnames:\n  0: tree\n")
t0=time.time(); m=YOLO('__MODEL__')
m.train(data=f'{D}/data.yaml', imgsz=__IMGSZ__, epochs=120, patience=__PATIENCE__, batch=8, seed=__SEED__, deterministic=True, fliplr=0.5, device=0, workers=4,
        project='/kaggle/working/runs', name='__NAME__', exist_ok=True, plots=True)
best=YOLO('/kaggle/working/runs/__NAME__/weights/best.pt'); res={}
for sp in ['val','test']:
    v=best.val(data=f'{D}/data.yaml', split=sp, imgsz=__IMGSZ__, batch=8, device=0, project='/kaggle/working/runs', name=f'eval_{sp}', exist_ok=True)
    res[sp]=dict(box_mAP50=float(v.box.map50), box_mAP50_95=float(v.box.map), pose_mAP50=float(v.pose.map50), pose_mAP50_95=float(v.pose.map))
with open('/kaggle/working/test_preds___NAME__.csv','w') as f:
    f.write('image,x0,y0,x1,y1,score,ku,kv,kconf,img_w,img_h\n')
    for r in best.predict(f'{D}/images/test', imgsz=__IMGSZ__, conf=0.001, device=0, verbose=False, stream=True):
        H,W=r.orig_shape
        for (a,b,c,d),s,k in zip(r.boxes.xyxyn.cpu().numpy(), r.boxes.conf.cpu().numpy(), r.keypoints.data.cpu().numpy()):
            f.write(f"{os.path.basename(r.path)},{a:.5f},{b:.5f},{c:.5f},{d:.5f},{s:.4f},{k[0,0]/W:.5f},{k[0,1]/H:.5f},{k[0,2]:.3f},{W},{H}\n")
import shutil; shutil.copy('/kaggle/working/runs/__NAME__/weights/best.pt','/kaggle/working/__NAME___best.pt')
res['train_minutes']=(time.time()-t0)/60; json.dump(res,open('/kaggle/working/results___NAME__.json','w'),indent=1); print(json.dumps(res,indent=1))
