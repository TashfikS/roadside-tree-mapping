"""Faster R-CNN (ResNet-50 FPN v2, torchvision) on the route-grouped Bangladesh split, seeds 0-2, COCO evaluator.
Generated by build_jobs.py. Output: results_frcnn.json."""
import os, glob, json, shutil, subprocess, csv, io, time
SPLIT_CSV = """__SPLIT_CSV__"""
R = glob.glob('/kaggle/input/**/roadside-trees-of-bangladesh-street-view', recursive=True)[0]
src = {'BD_740': f'{R}/Train/BD_740', 'BD_755': f'{R}/Train/BD_755', 'BD_Test_Set_270': f'{R}/Test/BD_Test_Set_270'}
D = '/kaggle/temp/ds'
for s in ['train','val','test']:
    os.makedirs(f'{D}/images/{s}', exist_ok=True); os.makedirs(f'{D}/labels/{s}', exist_ok=True)
n = {'train':0,'val':0,'test':0}
for r in csv.DictReader(io.StringIO(SPLIT_CSV)):
    stem = f"{r['folder']}_{r['id']}"; p = f"{src[r['folder']]}/{r['id']}"
    os.symlink(p+'.jpg', f"{D}/images/{r['split']}/{stem}.jpg")
    shutil.copy(p+'.txt', f"{D}/labels/{r['split']}/{stem}.txt"); n[r['split']] += 1
open(f'{D}/data.yaml','w').write(f"path: {D}\ntrain: images/train\nval: images/val\ntest: images/test\nnames:\n  0: tree\n")

import torch, torchvision, numpy as np, random
from PIL import Image
from torchvision.models.detection import fasterrcnn_resnet50_fpn_v2, FasterRCNN_ResNet50_FPN_V2_Weights
from torchvision.models.detection.faster_rcnn import FastRCNNPredictor
import torchvision.transforms.functional as TF
subprocess.run("pip install -q pycocotools", shell=True)
from pycocotools.coco import COCO; from pycocotools.cocoeval import COCOeval
def load(split):
    out=[]
    for p in sorted(glob.glob(f'{D}/images/{split}/*.jpg')):
        bx=[list(map(float,l.split()[1:5])) for l in open(p.replace('/images/','/labels/')[:-4]+'.txt') if l.strip()]
        out.append((p,bx))
    return out
class DS(torch.utils.data.Dataset):
    def __init__(s,items,train): s.items=items; s.train=train
    def __len__(s): return len(s.items)
    def __getitem__(s,i):
        p,bx=s.items[i]; im=Image.open(p).convert('RGB'); W,H=im.size; sc=1024/max(W,H); im=im.resize((round(W*sc),round(H*sc))); W,H=im.size
        b=torch.tensor([[ (x-w/2)*W,(y-h/2)*H,(x+w/2)*W,(y+h/2)*H] for x,y,w,h in bx],dtype=torch.float32).reshape(-1,4)
        t=TF.to_tensor(im)
        if s.train and random.random()<0.5: t=t.flip(-1); b=b[:,[2,1,0,3]]; b[:,0]=W-b[:,0]; b[:,2]=W-b[:,2]
        return t, dict(boxes=b, labels=torch.ones(len(b),dtype=torch.int64))
def evaluate(model, items):
    model.eval(); gt=dict(images=[],annotations=[],categories=[dict(id=1,name='tree')]); dt=[]; aid=0
    with torch.no_grad():
        for i,(p,bx) in enumerate(items):
            t,tg=DS([(p,bx)],False)[0]; H,W=t.shape[1:]
            gt['images'].append(dict(id=i,width=W,height=H))
            for b in tg['boxes'].tolist(): aid+=1; gt['annotations'].append(dict(id=aid,image_id=i,category_id=1,bbox=[b[0],b[1],b[2]-b[0],b[3]-b[1]],area=(b[2]-b[0])*(b[3]-b[1]),iscrowd=0))
            o=model([t.cuda()])[0]
            for b,s in zip(o['boxes'].cpu().tolist(),o['scores'].cpu().tolist()): dt.append(dict(image_id=i,category_id=1,bbox=[b[0],b[1],b[2]-b[0],b[3]-b[1]],score=s))
    C=COCO(); C.dataset=gt; C.createIndex(); Dt=C.loadRes(dt) if dt else None
    E=COCOeval(C,Dt,'bbox'); E.params.maxDets=[1,10,300]; E.evaluate(); E.accumulate(); E.summarize()
    return dict(mAP50_95=float(E.stats[0]), mAP50=float(E.stats[1]), mAP75=float(E.stats[2]))
tr,va,te=load('train'),load('val'),load('test'); allres={}
for SEED in (0,1,2):
    random.seed(SEED); np.random.seed(SEED); torch.manual_seed(SEED)
    m=fasterrcnn_resnet50_fpn_v2(weights=FasterRCNN_ResNet50_FPN_V2_Weights.COCO_V1, min_size=1024, max_size=1024, box_detections_per_img=300)
    m.roi_heads.box_predictor=FastRCNNPredictor(m.roi_heads.box_predictor.cls_score.in_features,2); m.cuda()
    dl=torch.utils.data.DataLoader(DS(tr,True),batch_size=4,shuffle=True,num_workers=4,collate_fn=lambda b:tuple(zip(*b)))
    opt=torch.optim.SGD([p for p in m.parameters() if p.requires_grad],lr=0.01,momentum=0.9,weight_decay=1e-4)
    E_=30; sch=torch.optim.lr_scheduler.OneCycleLR(opt,max_lr=0.01,total_steps=E_*len(dl),pct_start=0.1)
    best=(-1,None)
    for ep in range(E_):
        m.train()
        for ims,tgs in dl:
            loss=sum(m([i.cuda() for i in ims],[{k:v.cuda() for k,v in t.items()} for t in tgs]).values()); opt.zero_grad(); loss.backward(); opt.step(); sch.step()
        if ep>=9 and ep%3==2:
            v=evaluate(m,va)
            if v['mAP50_95']>best[0]: best=(v['mAP50_95'],{k:x.detach().cpu().clone() for k,x in m.state_dict().items()})
        print(SEED,ep,flush=True)
    m.load_state_dict(best[1]); allres[f'seed{SEED}']=dict(val=evaluate(m,va),test=evaluate(m,te))
    json.dump(allres,open('/kaggle/working/results_frcnn.json','w'),indent=1); print(json.dumps(allres[f'seed{SEED}']))
